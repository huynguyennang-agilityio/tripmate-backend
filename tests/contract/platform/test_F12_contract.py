"""F12 Contract publishing: cases F12-1, F12-2 (level C), and F12-3 (epic-11 spec, section 2.10).

The contract is generated by `python -m app.platform.contract generate <path>` in a new
process with no PostgreSQL or Redis address, as the CI job `contract` does.
"""

from __future__ import annotations

import json
from pathlib import Path

from tests.contract.platform.f12_support import (
    MODULE_PREFIX,
    generate,
    run_contract,
    stub_api_source,
)
from tests.support import APP_DIR


def test_F12_1_generating_openapi_json_twice_gives_the_same_file(tmp_path: Path) -> None:
    first, second = tmp_path / "first" / "openapi.json", tmp_path / "second" / "openapi.json"
    first.parent.mkdir()
    second.parent.mkdir()

    # Two separate processes, with different hash seeds, so no ordering can hide behind one.
    contract = generate(first, PYTHONHASHSEED="1")
    generate(second, PYTHONHASHSEED="2")

    assert "openapi" in contract
    assert f"{MODULE_PREFIX}/health" in contract["paths"]
    assert first.read_bytes() == second.read_bytes(), "the two generated files differ"


def test_F12_2_contract_marks_a_stub_route_x_stub_true(tmp_path: Path, module_folder) -> None:
    name = module_folder({"__init__.py": ""})
    segment = name.replace("_", "-")
    (APP_DIR / name / "api.py").write_text(stub_api_source(segment), encoding="utf-8")

    contract = generate(tmp_path / "openapi.json")

    path = f"{MODULE_PREFIX}/{segment}"
    assert path in contract["paths"], f"{path} is not in the contract"
    assert contract["paths"][path]["get"].get("x-stub") is True
    # A route that is not a stub is not marked.
    assert contract["paths"][f"{MODULE_PREFIX}/health"]["get"].get("x-stub") is not True


def test_F12_3_stub_response_schema_without_example_fails_the_check_naming_the_operation(
    tmp_path: Path, module_folder
) -> None:
    from app.platform.contract import check_examples

    name = module_folder({"__init__.py": ""})
    # Neither segment is a prefix of the other, so neither operation's
    # "<METHOD> <path>" is a substring of the other's.
    good, bare = name.replace("_", "-"), f"bare-{name.replace('_', '-')}"
    good_operation, bare_operation = f"GET {MODULE_PREFIX}/{good}", f"GET {MODULE_PREFIX}/{bare}"
    api = APP_DIR / name / "api.py"

    # Control: every stub's response schema has an example, so the check passes.
    api.write_text(stub_api_source(good), encoding="utf-8")
    passing = tmp_path / "passing.json"
    assert check_examples(generate(passing)) == []
    result = run_contract("check", str(passing))
    assert result.returncode == 0, (
        f"check exited {result.returncode}: {result.stdout}{result.stderr}"
    )

    # A second stub whose response schema has no example.
    api.write_text(stub_api_source(good, bare_segment=bare), encoding="utf-8")
    failing = tmp_path / "failing.json"
    contract = generate(failing)

    problems = check_examples(contract)
    assert problems, "the check passed a stub with no example"
    assert any(bare_operation in problem for problem in problems), problems
    assert not any(good_operation in problem for problem in problems), problems

    result = run_contract("check", str(failing))
    output = result.stdout + result.stderr
    assert result.returncode != 0, f"check exited 0 on a stub with no example: {output}"
    assert bare_operation in output
    assert good_operation not in output

    # The function takes the contract as read from the file, unchanged.
    assert check_examples(json.loads(failing.read_text(encoding="utf-8"))) == problems
